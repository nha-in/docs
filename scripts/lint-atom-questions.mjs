#!/usr/bin/env node
// Warns when an atom's body has changed since its questions were
// generated, and fails when an atom has no questions at all. The hash is
// the same sha256 prefix mcp/internal/catalogue/questions.go computes
// (BodyHash: "sha256:" + first 16 hex chars of sha256(atom.Body), where
// Atom.Body is the post-frontmatter text with leading/trailing whitespace
// trimmed), so the two never disagree about what "stale" means.
import {readFileSync, existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join} from 'node:path';
import {loadAtoms, root} from './lib/atoms.mjs';

const path = join(root, 'catalogue', 'shared', 'atom-questions.json');
if (!existsSync(path)) {
  // The file is generated by a Bedrock-backed command (cd mcp && go run
  // ./cmd/questiongen) that is deferred on this branch, so its absence is
  // not a lint failure: CI stays green until the generator runs.
  console.warn('lint-atom-questions: atom-questions.json is absent; naive phrasings match on prose only. The generator (cmd/questiongen) lands with task B2 of the routed retrieval plan.');
  process.exit(0);
}
const questions = JSON.parse(readFileSync(path, 'utf8'));
const hash = (body) => 'sha256:' + createHash('sha256').update(body.trim()).digest('hex').slice(0, 16);

const {atoms} = loadAtoms();
let missing = 0, stale = 0;
for (const atom of atoms.values()) {
  const q = questions[atom.fm.id];
  if (!q || !q.questions?.length) { console.error(`  no questions: ${atom.fm.id}`); missing++; continue; }
  if (q.body_hash !== hash(atom.body)) { console.warn(`  stale: ${atom.fm.id}`); stale++; }
}
console.log(`lint-atom-questions: ${Object.keys(questions).length} atoms with questions, ${stale} stale, ${missing} missing`);
if (missing) process.exit(1);
