// Stamps every NHCX skill router with where it came from, how to tell when it
// has gone stale, and what its claims actually rest on.
//
// The ABDM skills get this for free: they are compiled here, so the compiler
// writes the catalogue version and the snapshot warning into every SKILL.md.
// The NHCX skills are copied in from github.com/nha-in/nhcx-skills instead, so
// nothing stamped them and an agent reading one could not tell a folder taken
// in September from the current one. This writes the same three statements
// into the committed routers, from facts counted in this repository rather
// than typed in by hand.
//
// The block is generated. Everything outside it still comes from upstream and
// is still edited there, per plugins/nhcx/skills/README.md.
//
// Usage: node scripts/stamp-nhcx-skills.mjs [--check]
import {readdirSync, readFileSync, writeFileSync, existsSync} from 'node:fs';
import {join} from 'node:path';
import {root, loadAtoms} from './lib/atoms.mjs';
import {NHCX, nhcxEntry} from './lib/nhcx-skills.mjs';
import {tryAsking, IDLE_RULE} from './lib/try-asking.mjs';

const check = process.argv.includes('--check');
const skillsDir = join(root, 'plugins', 'nhcx', 'skills');

// Where the folders were taken from. Recorded in the skills README, which is
// the only place this repository states it, so it is read rather than copied.
const README = join(skillsDir, 'README.md');
function upstream() {
  const raw = readFileSync(README, 'utf8');
  const m = raw.match(/They come from ([^\s,]+), taken from its working tree on\s+([^,]+), over commit ([0-9a-f]+)\./s);
  if (!m) throw new Error('plugins/nhcx/skills/README.md no longer states the upstream repo, date and commit');
  return {repo: m[1], taken: m[2].replace(/\s+/g, ' ').trim(), commit: m[3]};
}

/** How many NHCX atoms the Catalogue holds. */
function catalogueCounts() {
  return {nhcxAtoms: [...loadAtoms().atoms.values()].filter((a) => a.fm.gateway === 'nhcx').length};
}

const OPEN = '<!-- provenance: generated by scripts/stamp-nhcx-skills.mjs, do not edit by hand -->';
const CLOSE = '<!-- /provenance -->';

/** The folder's own directories, listed as a reader would name them. */
function folders(slug) {
  const dirs = readdirSync(join(skillsDir, slug), {withFileTypes: true})
    .filter((entry) => entry.isDirectory())
    .map((entry) => `\`${entry.name}/\``)
    .sort();
  return dirs.length > 1 ? `${dirs.slice(0, -1).join(', ')} and ${dirs.at(-1)}` : dirs.join('');
}

/** The prompts a person can paste once this skill is installed. */
function tryAskingLines(slug) {
  if (!NHCX[slug]) return [];
  const prompts = tryAsking(nhcxEntry(slug, join(skillsDir, slug)));
  return ['', '**Try asking**', '', ...prompts.map((p) => `- "${p}"`), '', IDLE_RULE];
}

function block(slug) {
  const {repo, taken, commit} = upstream();
  const {nhcxAtoms} = catalogueCounts();

  return [
    OPEN,
    `Copied from ${repo} on ${taken}, over commit \`${commit}\`. The NHCX documentation is the place to look when this folder does not carry enough.`,
    '',
    `This folder is a snapshot. Re-download the whole folder from the portal's /skills/${slug}/ path when it is older than the work you are doing: this router and every file under ${folders(slug)}. Fetching this file alone leaves its pointers aimed at files you do not have.`,
    '',
    `If the nhcx-docs MCP server is connected, trust its answers over this folder. It serves the Catalogue live, which holds ${nhcxAtoms} NHCX atoms, and this folder cites none of them.`,
    '',
    `What the claims here rest on. The protocol comes from the knowledge source the skill records at its first step: the nhcx-docs MCP server, or a release of the NHCX package checked against its \`MANIFEST\`. What was seen only on the NHCX sandbox is marked [SANDBOX], and what depends on the payer is marked [PAYER].`,
    ...tryAskingLines(slug),
    CLOSE,
  ].join('\n');
}

/**
 * Puts the block straight before the router's first H1, replacing any earlier
 * one. Before, not after: the first heading of a router opens the instructions
 * an agent must read first, and the block must not split them.
 */
function stamped(raw, slug) {
  const body = raw.replace(new RegExp(`${OPEN}[\\s\\S]*?${CLOSE}\\n\\n?`), '');
  const h1 = body.match(/^# .+$/m);
  if (!h1) throw new Error(`${slug}/SKILL.md has no H1 to stamp before`);
  const at = body.indexOf(h1[0]);
  return `${body.slice(0, at)}${block(slug).replace(/^\n/, '')}\n\n${body.slice(at)}`;
}

const stale = [];
let written = 0;
for (const slug of readdirSync(skillsDir).sort()) {
  const file = join(skillsDir, slug, 'SKILL.md');
  if (!existsSync(file)) continue; // README.md and other non-skill entries
  const raw = readFileSync(file, 'utf8');
  const next = stamped(raw, slug);
  if (next === raw) continue;
  if (check) stale.push(slug);
  else {
    writeFileSync(file, next);
    written += 1;
    console.log(`stamped ${slug}/SKILL.md`);
  }
}

if (check && stale.length) {
  console.error(`${stale.length} NHCX skill router(s) carry no current provenance block: ${stale.join(', ')}`);
  console.error('Run: node scripts/stamp-nhcx-skills.mjs');
  process.exit(1);
}
console.log(check ? 'Every NHCX skill router carries a current provenance block.' : `${written} router(s) stamped.`);
